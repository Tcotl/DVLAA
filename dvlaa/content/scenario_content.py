def apply_owasp_scenarios(challenges: list[dict]) -> None:
    for challenge in challenges:
        for sub_level in challenge["sub_levels"]:
            sub_level.update(OWASP_SCENARIOS[(challenge["id"], sub_level["sub"])])


def apply_agent_scenarios(challenges: list[dict]) -> None:
    for challenge in challenges:
        challenge.update(AGENT_SCENARIOS[challenge["id"]])


def apply_extended_scenarios(challenges: list[dict]) -> None:
    for challenge in challenges:
        challenge.update(EXTENDED_SCENARIOS[challenge["id"]])
