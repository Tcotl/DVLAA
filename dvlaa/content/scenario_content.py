def apply_owasp_scenarios(challenges: list[dict]) -> None:
    for challenge in challenges:
        context = OWASP_REAL_CONTEXTS[challenge["id"]]
        for sub_level in challenge["sub_levels"]:
            scenario = dict(OWASP_SCENARIOS[(challenge["id"], sub_level["sub"])])
            raw_description = str(scenario.get("description", ""))
            task_objective = raw_description.split("任务目标：", 1)[-1].strip()
            sub_level.update(context)
            sub_level.update(scenario)
            if challenge["id"] == 10:
                sub_level["audit_focus"] = {
                    1: "长输出造成的资源消耗是否有最大令牌预算、超时和截断策略。",
                    2: "工具扇出是否有调用数量、并发和下游配额限制。",
                    3: "请求洪峰是否有会话、IP、租户级速率限制和熔断。",
                }.get(sub_level["sub"], context["audit_focus"])
            sub_level["background"] = context["background"]
            sub_level["event_background"] = context["background"]
            sub_level["task_objective"] = task_objective
            sub_level["description"] = f"事件背景：{context['background']} 任务目标：{task_objective}"
            sub_level["investigation_steps"] = [
                "先完成一条不涉及敏感资产的正常业务请求，记录模型回答、工具状态和响应字段。",
                f"围绕“{sub_level['name']}”只改变一个输入变量，比较正常路径和异常路径的行为差异。",
                f"检查是否出现与“{context['protected_assets']}”相关的异常输出，并记录触发前后的上下文或状态变化。",
                f"从服务端实现确认“{context['audit_focus']}”，再验证漏洞证据而不是只看页面提示。",
                f"最后根据“{context['repair_focus']}”设计修复，并用正常业务和攻击请求各回归一次。",
            ]


